        private static float Encode255(float linear)
        {
            return UiIconShade.LinearToSrgb(linear) * 255f;
        }

        /// <summary>
        /// T5 · the twin at render()'s own sampling (64 px cell: footprint ≤ 2 AP, so the slope filter is the reference's
        /// central difference) and without the D6 ceiling lands in the byte render() wrote. render() truncates
        /// (astype('uint8')), so the twin's value must lie in [ref, ref + 1) - ±1/255 - with 0.05 for float32.
        /// </summary>
        [Test]
        public void T5_Ikiz_ReferansRenderIle_8BitIcinde()
        {
            var failures = new List<string>();
            foreach (Row r in Reference)
            {
                Color tint = new Color(UiIconShade.SrgbToLinear(r.R / 255f), UiIconShade.SrgbToLinear(r.G / 255f), UiIconShade.SrgbToLinear(r.B / 255f), 1f);
                float boost = UiIconShade.Boost(r.Sd, new Vector2(r.Gx, r.Gy), 1f, new Vector2(r.X, r.Y), r.Sheen, 1f, UiIconShade.SheenPeak);
                Color lit = UiIconShade.Lit(tint, boost);
                float[] twin = { Encode255(lit.r), Encode255(lit.g), Encode255(lit.b) };
                int[] reference = { r.OutR, r.OutG, r.OutB };
                for (int c = 0; c < 3; c++)
                {
                    float d = twin[c] - reference[c];
                    if (d < -0.05f || d > 1.05f)
                    {
                        failures.Add("tint " + r.R + "," + r.G + "," + r.B + " sheen " + r.Sheen + " @" + r.X + "," + r.Y + " ch" + c
                            + ": twin " + twin[c].ToString("0.00", CultureInfo.InvariantCulture) + " ref " + reference[c]);
                    }
                }
            }

            Assert.IsEmpty(failures, "render() paritesi:\n" + string.Join("\n", failures));
        }

        /// <summary>
        /// T5 · the light alone: on a tint × boost grid (linear, every corner and mid tone) no channel ever falls under its tint
        /// and more boost never darkens. Row d's ink comes after it, within its ceiling (<see cref="RowD_Taban_TintCarpiTavan_IhlalSifir"/>).
        /// </summary>
        [Test]
        public void T5_RenkTabani_TintBoostIzgarasi_IhlalSifir()
        {
            float[] levels = { 0f, 0.002f, 0.02f, 0.1f, 0.25f, 0.5f, 0.75f, 0.9f, 1f };
            float[] boosts = { 0f, 0.01f, 0.05f, 0.085f, 0.1f, 0.25f, 0.5f, 0.75f, 1f };
            int violations = 0, cases = 0;
            string first = null;
            foreach (float r in levels)
            {
                foreach (float g in levels)
                {
                    foreach (float b in levels)
                    {
                        var tint = new Color(r, g, b, 1f);
                        Color previous = tint;
                        foreach (float boost in boosts)
                        {
                            cases++;
                            Color lit = UiIconShade.Lit(tint, boost);
                            bool under = lit.r < tint.r || lit.g < tint.g || lit.b < tint.b;
                            bool darker = lit.r < previous.r - 1e-6f || lit.g < previous.g - 1e-6f || lit.b < previous.b - 1e-6f;
                            if (under || darker)
                            {
                                violations++;
                                first = first ?? ("tint " + tint + " boost " + boost + " → " + lit);
                            }

                            previous = lit;
                        }
                    }
                }
            }

            Assert.Greater(cases, 6000);
            Assert.AreEqual(0, violations, "ışık yalnız ekler (IK-M5), artan boost'ta azalmaz: " + first);
        }

        /// <summary>
        /// D6 + IK-M15: the sheen band is held to DD_UI_GLINT_MAX_BRIGHTNESS (0.25 - its 0.45 peak would pass the glint
        /// token) and scales with FlashScale (0.4 under Reduce Flashes); the glow scales with it too; −1 is off.
        /// </summary>
        [Test]
        public void D6_SheenTavaniGlintTokeni_FlashOlcegiyle()
        {
            Assert.AreEqual(UiMaterialSpec.GlintMaxBrightness, UiIconShade.SheenCeiling, "D6: tavan = mevcut glint token'ı");
            Assert.AreEqual(0.25f, UiIconShade.SheenCeiling, 1e-6f);

            // The band centre at sheen 0.5 sits where x/63 + y/160 = 0.75: x = 63 · 0.75 at y = 0. On the plateau the rest
            // of the boost is the flat key, 0.12 · 0.707.
            var index = new Vector2(63f * 0.75f, 0f);
            float plateau = UiIconShade.Boost(20f, Vector2.zero, 2f, index, -1f);
            Assert.AreEqual(0.12f * 0.707f, plateau, 1e-4f, "plato: yalnız anahtar ışık");
            float full = UiIconShade.Boost(20f, Vector2.zero, 2f, index, 0.5f, 1f) - plateau;
            float reduced = UiIconShade.Boost(20f, Vector2.zero, 2f, index, 0.5f, UiSettings.ReducedFlashScale) - plateau;
            float raw = UiIconShade.Boost(20f, Vector2.zero, 2f, index, 0.5f, 1f, UiIconShade.SheenPeak) - plateau;
            Assert.AreEqual(0.25f, full, 1e-4f, "sheen tepe = 0,25 (D6)");
            Assert.AreEqual(0.25f * UiSettings.ReducedFlashScale, reduced, 1e-4f, "flaşı azalt: × 0,4 (IK-M15)");
            Assert.AreEqual(0.45f, raw, 1e-4f, "render() tepesi 0,45 (tavansız ikiz)");

            foreach (float s in new[] { 0f, 0.5f, 1f })
            {
                float glow = UiIconShade.GlowAlpha(UiIconShade.GlowChannelMax, -0.5f, 0f, s);
                Assert.AreEqual(UiIconShade.GlowAlpha(UiIconShade.GlowChannelMax, -0.5f, 0f, s, UiSettings.ReducedFlashScale), glow * UiSettings.ReducedFlashScale, 1e-6f,
                    "glow × FlashScale (IK-M15)");
                Assert.LessOrEqual(glow, UiMaterialSpec.IconGlowAlpha + UiMaterialSpec.IconGlowAlphaRamp * s + 1e-6f, "glow tavanı = d satırı 0,07 + 0,05 s");
            }

            // WP-098A row d: the glow's α at its peak ramps with the size, 0.07 at 24 px → 0.12 from 40 (AD §2).
            Assert.AreEqual(0.07f, UiIconShade.GlowAlpha(UiIconShade.GlowChannelMax, 0f, 0f, UiIconShade.SizeRamp(24f)), 1e-6f);
            Assert.AreEqual(0.12f, UiIconShade.GlowAlpha(UiIconShade.GlowChannelMax, 0f, 0f, UiIconShade.SizeRamp(40f)), 1e-6f);
        }

        /// <summary>
        /// T2 (twin): the outer layers' mask is exactly 0 wherever the glyph has any coverage - for every distance, at the S /
        /// M / L footprints straight and diagonal, with and without spread - and is fully on by 1.5 px beyond the edge.
        /// </summary>
        [Test]
        public void T2Ikiz_DisKatman_KapsamOlanPikseldeSifir()
        {
            float[] footprints = { 1.6f, 2f, 1.6f * 1.4142f, 2.6667f, 2.6667f * 1.4142f };
            float[] spreads = { 0f, 0.2f, 0.3f, 0.4f };
            int leaks = 0;
            foreach (float w in footprints)
            {
                foreach (float spread in spreads)
                {
                    for (float sd = -10f; sd <= 10f; sd += 0.005f)
                    {
                        if (UiIconShade.Coverage(sd, w, spread) > 0f && UiIconShade.Outside(sd, w, spread) > 0f)
                        {
                            leaks++;
                        }
                    }

                    float beyond = -1.5f * w - UiIconShade.SpreadDilation(spread) - 1e-3f;
                    Assert.AreEqual(1f, UiIconShade.Outside(beyond, w, spread), 1e-5f, "1,5 px dışarıda maske tam");
                    Assert.AreEqual(0f, UiIconShade.Coverage(beyond, w, spread), 1e-6f);
                }
            }

            Assert.AreEqual(0, leaks, "dış katman maskesi kapsamı olan bir mesafede açık");
        }

