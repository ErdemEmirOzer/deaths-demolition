        private static float LinearAlphaOf(Color fg, Color bg, float srgbAlpha)
        {
            float target = Luminance(new Color(
                UiIconShade.SrgbToLinear(fg.r * srgbAlpha + bg.r * (1f - srgbAlpha)),
                UiIconShade.SrgbToLinear(fg.g * srgbAlpha + bg.g * (1f - srgbAlpha)),
                UiIconShade.SrgbToLinear(fg.b * srgbAlpha + bg.b * (1f - srgbAlpha))));
            float f = Luminance(Linear(fg)), b = Luminance(Linear(bg));
            return (target - b) / (f - b);
        }

        private static Color Linear(Color c)
        {
            return new Color(UiIconShade.SrgbToLinear(c.r), UiIconShade.SrgbToLinear(c.g), UiIconShade.SrgbToLinear(c.b));
        }

        private static float Luminance(Color linear)
        {
            return 0.2126f * linear.r + 0.7152f * linear.g + 0.0722f * linear.b;
        }

        private static void Same(string text, string name, params float[] expected)
        {
            CollectionAssert.AreEqual(expected, Define(text, name), new Near(1e-6f), name + " ↔ UiIconShade");
        }

        /// <summary>The numbers of a <c>#define NAME value</c> line: a scalar, or the arguments of floatN(…); a trailing // comment is ignored.</summary>
        private static float[] Define(string text, string name)
        {
            Match m = Regex.Match(text, "^#define\\s+" + name + "\\s+(.+?)\\s*(?://.*)?$", RegexOptions.Multiline);
            Assert.IsTrue(m.Success, name + " tanımı yok");
            string value = m.Groups[1].Value.Trim();
            int open = value.IndexOf('(');
            if (open >= 0)
            {
                value = value.Substring(open + 1, value.LastIndexOf(')') - open - 1);
            }

            var numbers = new List<float>();
            foreach (string part in value.Split(','))
            {
                numbers.Add(float.Parse(part.Trim(), NumberStyles.Float, CultureInfo.InvariantCulture));
            }

            return numbers.ToArray();
        }

        private sealed class Near : System.Collections.IComparer
        {
            private readonly float _tolerance;

            public Near(float tolerance)
            {
                _tolerance = tolerance;
            }

            public int Compare(object x, object y)
            {
                float a = System.Convert.ToSingle(x), b = System.Convert.ToSingle(y);
                return Mathf.Abs(a - b) <= _tolerance + 1e-6f * Mathf.Max(Mathf.Abs(a), Mathf.Abs(b)) ? 0 : a.CompareTo(b);
            }
        }
    }
