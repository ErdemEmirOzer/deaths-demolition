using System;
using System.Globalization;
using System.IO;
using System.Text;
using DD.Prototype.Core.Config;
using DD.Prototype.Diagnostics.EditorTools;
using UnityEditor;
using UnityEngine;

namespace DD.Prototype.Weapons.EditorTools
{
    /// <summary>
    /// WP-042 · E · Time-to-kill table per classic weapon × tier × armour state, straight from
    /// the WP-041 <see cref="EconomySimulator"/> report (no second model: the numbers are the
    /// simulator's <c>ttkNoArmour / ttkArmoured / ttkExpected</c> at the sampled rounds, on the
    /// simulator's build path and 0.70 hit fraction). Written to
    /// <c>planning/work-packages/WP-042-TTK-TABLE.md</c>; batch:
    /// <c>-executeMethod DD.Prototype.Weapons.EditorTools.WeaponTtkTable.Write</c>.
    /// </summary>
    public static class WeaponTtkTable
    {
        public const string OutputRelative = "planning/work-packages/WP-042-TTK-TABLE.md";
        public static readonly int[] SampledRounds = { 1, 3, 5, 8, 10, 15 };

        [MenuItem("Tools/Deaths Demolition/Weapons/Write TTK Table (WP-042)")]
        public static void Write()
        {
            string repo = Path.GetFullPath(Path.Combine(Application.dataPath, "..", "..", ".."));
            string path = Path.Combine(repo, OutputRelative);
            string md = Build(null);
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, md, new UTF8Encoding(false));
            Debug.Log("[WeaponTtkTable] wrote " + path + " (" + md.Length + " chars)");
        }

        /// <summary>The markdown table for a config (null = the active config).</summary>
        public static string Build(PrototypeConfig config)
        {
            var o = new EconomySimulator.Options { config = config, firstRound = 1, lastRound = 15, seed = 1u };
            EconomySimulator.Report r = EconomySimulator.Run(o);
            CultureInfo ic = CultureInfo.InvariantCulture;
            var sb = new StringBuilder();
            sb.AppendLine("# WP-042 · TTK table (classic weapon × tier × armour)");
            sb.AppendLine();
            sb.AppendLine("Generated by `WeaponTtkTable.Write` from the WP-041 `EconomySimulator` report (schema `" + r.schema +
                          "`, seed " + r.seed + ", hit fraction " + r.hitFraction.ToString("0.00", ic) +
                          ", one purchase per round when affordable). Seconds to kill ONE target with the round's build: " +
                          "**none** = no armour, **full** = every piece the tier can carry, **exp.** = this round's simulated armour mix. " +
                          "PROTOTYPE-ONLY numbers (weapon damage / tier health / armour durability are the WP-000 placeholders); " +
                          "the WP-041 proposals Ö-3/Ö-4 are not applied. Regenerate after any weapon, tier or armour data change.");
            sb.AppendLine();
            for (int w = 0; w < r.weapons.Length; w++)
            {
                EconomySimulator.WeaponTrack t = r.weapons[w];
                sb.AppendLine("## " + t.rosterKey + " · " + t.weapon + " (unlock L" + t.unlockLevel + "; core " + t.coreBranches + ")");
                sb.AppendLine();
                sb.AppendLine("| R | build | DPS single | " + string.Join(" | ", TierHeaders(r)) + " |");
                sb.AppendLine("|---|---|---|" + Repeat("---|", r.tierNames.Length));
                for (int i = 0; i < SampledRounds.Length; i++)
                {
                    EconomySimulator.RoundRow row = FindRound(t, SampledRounds[i]);
                    if (row == null) continue;
                    sb.Append("| R").Append(row.round).Append(" | ").Append(row.build).Append(" | ")
                      .Append(row.sustainedDps.ToString("0.0", ic)).Append(" | ");
                    for (int k = 0; k < row.ttk.Length; k++)
                    {
                        EconomySimulator.TierTtk c = row.ttk[k];
                        if (c == null || c.count <= 0)
                        {
                            sb.Append("— | ");
                            continue;
                        }

                        sb.Append(c.ttkNoArmour.ToString("0.0", ic)).Append(" / ")
                          .Append(c.ttkArmoured.ToString("0.0", ic)).Append(" / ")
                          .Append(c.ttkExpected.ToString("0.0", ic)).Append(" | ");
                    }

                    sb.AppendLine();
                }

                sb.AppendLine();
            }

            sb.AppendLine("Cell = none / full / exp. seconds; — = the tier has not been introduced by that round. Flags raised by the simulator (owner S-02):");
            sb.AppendLine();
            int flagged = 0;
            for (int i = 0; i < r.flags.Length; i++)
            {
                if (r.flags[i].owner != "S-02") continue;
                sb.AppendLine("- [" + r.flags[i].severity + "] " + r.flags[i].band + " — " + r.flags[i].text);
                flagged++;
            }

            if (flagged == 0) sb.AppendLine("- none");
            return sb.ToString();
        }

        private static string[] TierHeaders(EconomySimulator.Report r)
        {
            var h = new string[r.tierNames.Length];
            for (int i = 0; i < h.Length; i++) h[i] = r.tierNames[i] + " none/full/exp.";
            return h;
        }

        private static string Repeat(string s, int n)
        {
            var sb = new StringBuilder();
            for (int i = 0; i < n; i++) sb.Append(s);
            return sb.ToString();
        }

        private static EconomySimulator.RoundRow FindRound(EconomySimulator.WeaponTrack t, int round)
        {
            for (int i = 0; i < t.rounds.Length; i++)
            {
                if (t.rounds[i].round == round) return t.rounds[i];
            }

            return null;
        }
    }
}
