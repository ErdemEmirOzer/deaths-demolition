                sb.Append("    \"").Append(Lower(elevations[i].ToString())).Append("\": { \"shadowRadius\": ").Append(Dim((int)UiElevationSpec.ShadowRadius(elevations[i])))
                  .Append(", \"shadowAlpha\": ").Append(F(UiElevationSpec.ShadowAlpha(elevations[i])))
