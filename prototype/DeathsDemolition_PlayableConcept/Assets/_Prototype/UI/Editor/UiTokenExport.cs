        private static void AppendJsonColours(StringBuilder sb, string group, bool trailingComma)
        {
            sb.Append("    \"").Append(group).Append("\": {\n");
            UiColor[] tokens = (UiColor[])Enum.GetValues(typeof(UiColor));
            for (int i = 0; i < tokens.Length; i++)
            {
                sb.Append("      \"").Append(tokens[i]).Append("\": { \"$type\": \"color\", \"$value\": \"").Append(HexOf(UiTokens.Get(tokens[i]))).Append("\" }")
                  .Append(i < tokens.Length - 1 ? ",\n" : "\n");
            }

            sb.Append(trailingComma ? "    },\n" : "    }\n");
        }

        // ------------------------------------------------------------------ style guide §2.2 UI table

        public static string BuildStyleGuideBlock()
        {
            var sb = new StringBuilder(4096);
            sb.Append(StyleGuideBegin).Append('\n');
            sb.Append("#### 2.2 UI · arayüz token tablosu (WP-068 token v3)\n\n");
            sb.Append("| token | Default | ColorBlindSafe |\n|---|---|---|\n");
            foreach (UiColor token in Enum.GetValues(typeof(UiColor)))
            {
                string def = null, cb = null;
                WithPalette(UiPalette.Default, () => def = HexOf(UiTokens.Get(token)));
                WithPalette(UiPalette.ColorBlindSafe, () => cb = HexOf(UiTokens.Get(token)));
                sb.Append("| `").Append(token).Append("` | ").Append(def).Append(" | ").Append(cb).Append(" |\n");
            }

            sb.Append('\n');
            sb.Append("UI rezerv kuralları (WP-068 AD MUST 3):\n");
            sb.Append("- **Altın** (`StateGold`, `BarSpecial`, `GoldLeaf` = kinpaku) yalnız para sayacı, fiyat ve Special HUD'dadır; tören **ginpaku**'dur (`SilverLeaf`, krem): madalya, NEW BEST, seviye.\n");
            sb.Append("- **Uyarı** (`StateWarning`) para altınından ayrıdır: ").Append(UiTokens.DistinctWarningHue ? "Amber300 #F7C766 (ΔL* 10,8)" : "renksiz (krem metin + kelime + şekil)")
              .Append("; aynı panelde uyarı ile odak altını buluşursa uyarı rengi odak halkasının yerini alır.\n");
            sb.Append("- **Şarjör/reload** (`BarReload`) Focus400'dür ve varak almaz (para değil, Special değil).\n");
            sb.Append("- **Fener parıltısı** (`LanternGlow`, Amber300) dekoratiftir, anlam taşımaz: yalnız menü plakasının fener maskesi, α ≤ 0,35 (nefes tabanı 0,19), altın bandının dışında. Durum tokenları dekorasyona bağlanmaz.\n");
            sb.Append("- **Sakura** (`AccentSakura`, `BarXp`) = NEW ve ilerleme; **vermilion** (`AccentPrimary`) = ekran/modal başına bir birincil CTA + başlık tiki + mühür.\n");
            sb.Append("- **İki yeşil**: Jade (`StateSuccess`, kazanılmış) ve Moss (`BarHealth`, can); renk körlüğü paletinde ikisi de indigo ailesine geçer.\n");
            sb.Append("- Durum hiçbir zaman yalnız renkle taşınmaz: kelime + şekil (renk körlüğü paleti, WCAG 1.4.1).\n");
            sb.Append(StyleGuideEnd).Append('\n');
            return sb.ToString();
        }

        /// <summary>The style guide with the generated block inserted (before §2.3) or replaced in place.</summary>
        public static string MergeIntoStyleGuide(string guide)
        {
            string block = BuildStyleGuideBlock();
            int begin = guide.IndexOf(StyleGuideBegin, StringComparison.Ordinal);
            if (begin >= 0)
            {
                int end = guide.IndexOf(StyleGuideEnd, begin, StringComparison.Ordinal);
                if (end >= 0)
                {
                    int after = end + StyleGuideEnd.Length;
                    if (after < guide.Length && guide[after] == '\n')
                    {
                        after++;
                    }

                    return guide.Substring(0, begin) + block + guide.Substring(after);
                }
            }

            int section = guide.IndexOf("\n### 2.3", StringComparison.Ordinal);
            if (section < 0)
            {
                return guide.TrimEnd('\n') + "\n\n" + block;
            }

            return guide.Substring(0, section + 1) + block + "\n" + guide.Substring(section + 1);
        }

        // ------------------------------------------------------------------ helpers

        public static string HexOf(Color c)
        {
            int r = Mathf.RoundToInt(Mathf.Clamp01(c.r) * 255f);
            int g = Mathf.RoundToInt(Mathf.Clamp01(c.g) * 255f);
            int b = Mathf.RoundToInt(Mathf.Clamp01(c.b) * 255f);
            int a = Mathf.RoundToInt(Mathf.Clamp01(c.a) * 255f);
            return a >= 255
                ? string.Format(CultureInfo.InvariantCulture, "#{0:X2}{1:X2}{2:X2}", r, g, b)
                : string.Format(CultureInfo.InvariantCulture, "#{0:X2}{1:X2}{2:X2}{3:X2}", r, g, b, a);
        }

        private static void WithPalette(UiPalette palette, Action body)
        {
            UiPalette before = UiTokens.Palette;
            UiTokens.Palette = palette;
            try
            {
                body();
            }
            finally
            {
                UiTokens.Palette = before;
            }
        }

        private static string F(float v)
        {
            return v.ToString("0.####", CultureInfo.InvariantCulture);
        }

        private static string Dim(int px)
        {
            return "{ \"$type\": \"dimension\", \"$value\": \"" + px.ToString(CultureInfo.InvariantCulture) + "px\" }";
        }

        private static string Lower(string name)
        {
            return char.ToLowerInvariant(name[0]) + name.Substring(1);
        }

        private static string Upper(string camel)
        {
            var sb = new StringBuilder(camel.Length + 8);
            for (int i = 0; i < camel.Length; i++)
            {
                char ch = camel[i];
                if (i > 0 && char.IsUpper(ch) && !char.IsUpper(camel[i - 1]))
                {
                    sb.Append('_');
                }

                sb.Append(char.ToUpperInvariant(ch));
            }

            return sb.ToString();
        }
