    /// <summary>
    /// WP-068 token v3 (direction §2): C# stays the single source; this builds the three
    /// derived artefacts as text - <c>UiTokens.hlsl</c> (S-07's Fx shader includes it),
    /// <c>ui-tokens.json</c> (DTCG, for Adobe swatches / docs) and the generated UI table
    /// in style guide §2.2. <see cref="UiTokenExporter"/> (DD/UI/Export Tokens) writes them; the
    /// EditMode freshness test rebuilds them and compares with what is on disk, so a token
    /// change without a re-export fails. Pure string building; lives in the Editor assembly so the
    /// UI runtime literal audit (no Turkish in runtime strings) does not see the style-guide text.
    /// </summary>
    public static class UiTokenExport
    {
        public const string HlslPath = "Assets/_Prototype/UI/Art/Shaders/UiTokens.hlsl";
        public const string JsonPath = "Assets/_Prototype/UI/Art/Tokens/ui-tokens.json";
        public const string StyleGuidePath = "Assets/_Art/StyleGuide/style-guide-v1.md";
        public const string StyleGuideBegin = "<!-- ui-tokens:begin (generated by DD/UI/Export Tokens from UiTokens.cs - do not edit by hand) -->";
        public const string StyleGuideEnd = "<!-- ui-tokens:end -->";

        private static readonly UiDuration[] Durations =
            { UiDuration.Instant, UiDuration.Fast, UiDuration.Base, UiDuration.Screen, UiDuration.Emphasis, UiDuration.Reveal };

        private static readonly UiEase[] Eases =
            { UiEase.Settle, UiEase.SettleLong, UiEase.Exit, UiEase.Move, UiEase.Brush };

        // ------------------------------------------------------------------ HLSL

        public static string BuildHlsl()
        {
            var sb = new StringBuilder(4096);
            sb.Append("// GENERATED by DD/UI/Export Tokens from UiTokens.cs / UiTokenFamilies.cs (WP-068 token v3). Do not edit.\n");
            sb.Append("// Colours are sRGB (gamma) - convert with SRGBToLinear in a linear-space shader.\n");
            sb.Append("#ifndef DD_UI_TOKENS_INCLUDED\n#define DD_UI_TOKENS_INCLUDED\n\n");

            WithPalette(UiPalette.Default, () => AppendHlslColours(sb, "DD_UI_"));
            sb.Append('\n');
            WithPalette(UiPalette.ColorBlindSafe, () => AppendHlslColours(sb, "DD_UI_CB_"));
            sb.Append('\n');

            foreach (UiDuration d in Durations)
            {
                sb.Append("#define DD_UI_DURATION_").Append(d.ToString().ToUpperInvariant()).Append(' ')
                  .Append(F(UiMotionTokens.Seconds(d))).Append('\n');
            }

            sb.Append('\n');
            foreach (UiEase e in Eases)
            {
                Vector4 p = UiEaseCurve.ControlPoints(e);
                sb.Append("#define DD_UI_EASE_").Append(e.ToString().ToUpperInvariant()).Append(" float4(")
                  .Append(F(p.x)).Append(", ").Append(F(p.y)).Append(", ").Append(F(p.z)).Append(", ").Append(F(p.w)).Append(")\n");
            }

            sb.Append('\n');
            foreach (UiMotionClass c in Enum.GetValues(typeof(UiMotionClass)))
            {
                sb.Append("#define DD_UI_MOTION_CLASS_").Append(c.ToString().ToUpperInvariant()).Append(' ').Append((int)c).Append('\n');
            }

            sb.Append('\n');
            sb.Append("#define DD_UI_STAMP_PEAK ").Append(F(UiMotionTokens.StampPeakScale)).Append('\n');
            sb.Append("#define DD_UI_STAMP_IN ").Append(F(UiMotionTokens.StampInSeconds)).Append('\n');
            sb.Append("#define DD_UI_LEAF_TILE_ALPHA ").Append(F(UiMaterialSpec.LeafTileAlpha)).Append('\n');
            sb.Append("#define DD_UI_GLINT_MAX_BRIGHTNESS ").Append(F(UiMaterialSpec.GlintMaxBrightness)).Append('\n');
            sb.Append("#define DD_UI_SHEEN_FIELD_ALPHA_MAX ").Append(F(UiMaterialSpec.SheenFieldAlphaMax)).Append('\n');
            sb.Append("#define DD_UI_WASHI_ALPHA_MAX ").Append(F(UiMaterialSpec.WashiAlphaMax)).Append('\n');
            // WP-081 ikon v2 B5b: the icon material's AD-owned numbers (D3 glow, D7 lob: sRGB colour, linear-blend alpha in w).
            sb.Append("#define DD_UI_ICON_GLOW_ALPHA ").Append(F(UiMaterialSpec.IconGlowAlpha)).Append('\n');
            sb.Append("#define DD_UI_ICON_GLOW_RADIUS ").Append(F(UiMaterialSpec.IconGlowRadiusAp)).Append('\n');
            Color lob = UiMaterialSpec.IconLobColour;
            sb.Append("#define DD_UI_ICON_LOB float4(").Append(F(lob.r)).Append(", ").Append(F(lob.g)).Append(", ").Append(F(lob.b))
              .Append(", ").Append(F(UiMaterialSpec.IconLobAlpha)).Append(")\n");
            sb.Append("\n#endif // DD_UI_TOKENS_INCLUDED\n");
            return sb.ToString();
        }

        private static void AppendHlslColours(StringBuilder sb, string prefix)
        {
            foreach (UiColor token in Enum.GetValues(typeof(UiColor)))
            {
                Color c = UiTokens.Get(token);
                sb.Append("#define ").Append(prefix).Append(Upper(token.ToString())).Append(" float4(")
                  .Append(F(c.r)).Append(", ").Append(F(c.g)).Append(", ").Append(F(c.b)).Append(", ").Append(F(c.a)).Append(")\n");
            }
        }

        // ------------------------------------------------------------------ JSON (DTCG)

