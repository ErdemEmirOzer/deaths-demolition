        {
            var sb = new StringBuilder(8192);
            sb.Append("{\n");
            sb.Append("  \"$description\": \"Deaths Demolition UI tokens v3 (WP-068). GENERATED from UiTokens.cs - do not edit.\",\n");
            sb.Append("  \"color\": {\n");
            WithPalette(UiPalette.Default, () => AppendJsonColours(sb, "default", true));
            WithPalette(UiPalette.ColorBlindSafe, () => AppendJsonColours(sb, "colorBlindSafe", false));
            sb.Append("  },\n");

            sb.Append("  \"duration\": {\n");
            for (int i = 0; i < Durations.Length; i++)
            {
                sb.Append("    \"").Append(Lower(Durations[i].ToString())).Append("\": { \"$type\": \"duration\", \"$value\": \"")
                  .Append((int)Durations[i]).Append("ms\" }").Append(i < Durations.Length - 1 ? ",\n" : "\n");
            }

            sb.Append("  },\n");
            sb.Append("  \"cubicBezier\": {\n");
